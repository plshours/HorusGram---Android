def drawable(parts):
    paths = []
    for data, fill in parts:
        attrs = [f'android:pathData="{data}"',
                 'android:strokeColor="#FFFFFFFF"',
                 f'android:strokeWidth="{LINE}"',
                 'android:strokeLineCap="square"',
                 'android:strokeLineJoin="miter"']
        if fill == 1:
            attrs += ['android:fillColor="#FFFFFFFF"', f'android:fillAlpha="{DUO}"']
        elif fill == 2:
            attrs += ['android:fillColor="#FFFFFFFF"']
        paths.append('    <path\n        ' + '\n        '.join(attrs) + ' />')
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- HorusGram: generated by Tools/horusgram/make_icons.py. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="24dp"\n    android:height="24dp"\n'
            '    android:viewportWidth="24"\n    android:viewportHeight="24">\n'
            + '\n'.join(paths) + '\n</vector>\n')

out = sys.argv[1]
for name, parts in ICONS.items():
    with open(f'{out}/horus_ic_{name}.xml', 'w', encoding='utf-8', newline='\n') as f:
        f.write(drawable(parts))
