#!/usr/bin/env python3
# HorusGram for Android - writes the icon set of HORUSGRAM_DESIGN.md as
# vector drawables (res/drawable/horus_ic_*.xml).
#
# Usage: make_icons.py <res/drawable>
#
# One 24x24 grid, a 1.7 line with square ends and mitred corners, and the
# main shape of each icon filled at 22%: the "duotone" style. The icons are
# white and get tinted where they are shown.
import sys

LINE = 1.7
DUO = 0.22

def circle(cx, cy, r):
    return f'M{cx - r},{cy}a{r},{r} 0 1,0 {2 * r},0a{r},{r} 0 1,0 {-2 * r},0z'

def ellipse(cx, cy, rx, ry):
    return f'M{cx - rx},{cy}a{rx},{ry} 0 1,0 {2 * rx},0a{rx},{ry} 0 1,0 {-2 * rx},0z'

def rect(x, y, w, h, r):
    return (f'M{x + r},{y}h{w - 2 * r}a{r},{r} 0 0,1 {r},{r}v{h - 2 * r}'
            f'a{r},{r} 0 0,1 {-r},{r}h{-(w - 2 * r)}a{r},{r} 0 0,1 {-r},{-r}'
            f'v{-(h - 2 * r)}a{r},{r} 0 0,1 {r},{-r}z')

